# Print a Markdown catalog of the registered plugins (and optionally of the
# shipped profiles), generated from the registry so it never drifts from the code.
#
# Usage:
#   python tools\modegen_catalog.py [--output FILE.md]
#                                   [--profiles-output FILE.md]
#                                   [--no-user-plugins] [--plugin-dir DIR ...]
#
# Without --output the plugin catalog is printed to stdout.
# The catalog covers the built-ins plus the shipped user_plugins/ template.

import argparse
import os

import _common

parser = argparse.ArgumentParser(description="Markdown catalog of modegen plugins/profiles.")
parser.add_argument("--output", default=None, help="Write the plugin catalog here.")
parser.add_argument("--profiles-output", default=None, help="Also write a profile catalog here.")
_common.add_plugin_args(parser)
_common.add_version_arg(parser)
args = parser.parse_args()

from modegen import CATEGORIES, Profile, __version__  # noqa: E402

PRECOMPUTE = ("fracture.generator", "fracture.weights", "fracture.init",
              "elastic.generator", "plastic.generator", "plastic.weights")


def cell(text):
    return str(text).replace("|", "\\|").replace("\n", " ")


def fmt_default(p):
    if p["plugin"]:
        d = p["default"]
        if isinstance(d, dict) and "plugin" in d:
            return f"`{d['plugin']}`"
        return "`[]`" if p["many"] and not d else f"`{d!r}`"
    return f"`{p['default']!r}`"


def plugin_catalog(reg):
    lines = [
        "# Plugin catalog",
        "",
        f"Generated by `tools/modegen_catalog.py` from the plugin registry (modegen {__version__}).",
        "Do not edit by hand; regenerate after changing a plugin. How to write a",
        "plugin and the category contracts: see the README.",
        "",
    ]
    for group, cats in (("Precompute", [c for c in CATEGORIES if c in PRECOMPUTE]),
                        ("Runtime", [c for c in CATEGORIES if c not in PRECOMPUTE])):
        lines += [f"## {group} plugins", ""]
        for cat in cats:
            infos = reg.describe(cat)
            if not infos:
                continue
            lines += [f"### `{cat}`", ""]
            for d in infos:
                lines += [f"#### `{d['name']}` (v{d['version']})", ""]
                if d["description"]:
                    lines += [d["description"], ""]
                lines += [f"Source: `{d['source']}`", ""]
                if d["params"]:
                    lines += ["| parameter | default | description |", "|---|---|---|"]
                    for k, p in d["params"].items():
                        doc = p["doc"]
                        if p["plugin"]:
                            doc = f"nested `{p['plugin']}`{' list' if p['many'] else ''} plugin. {doc}"
                        if p["choices"]:
                            doc += f" (choices: {', '.join(repr(c) for c in p['choices'])})"
                        lines.append(f"| `{k}` | {cell(fmt_default(p))} | {cell(doc)} |")
                    lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def slot_name(spec):
    if spec is None:
        return "disabled"
    if isinstance(spec, dict):
        return f"`{spec.get('plugin')}`"
    return f"`{spec}`"


def profile_catalog(reg):
    lines = [
        "# Profile catalog",
        "",
        f"Generated by `tools/modegen_catalog.py` from `profiles/*.json` (modegen {__version__}).",
        "Every profile is merged onto the `realistic` defaults; see",
        "the README for the merge rules.",
        "",
    ]
    for name in Profile.available():
        p = Profile.load(name)
        errs = p.validate(reg)
        rt = p.get("runtime") or {}
        tools = ", ".join(f"`{t}` ({slot_name(s)})" for t, s in (rt.get("tools") or {}).items())
        lines += [
            f"## `{name}`", "",
            p.data.get("description", ""), "",
            "| slot | plugin |", "|---|---|",
            f"| precompute.fracture | {slot_name(p.get('precompute.fracture'))} |",
            f"| precompute.elastic | {slot_name(p.get('precompute.elastic'))} |",
            f"| precompute.plastic | {slot_name(p.get('precompute.plastic'))} |",
            f"| runtime.router | {slot_name(rt.get('router'))} |",
            f"| runtime.plastic_response | {slot_name(rt.get('plastic_response'))} |",
            f"| runtime.fracture_response | {slot_name(rt.get('fracture_response'))} |",
            f"| runtime.post | {', '.join(slot_name(s) for s in (rt.get('post') or [])) or 'none'} |",
            f"| tools (default `{rt.get('default_tool')}`) | {tools} |",
            "",
            f"Schema version {p.schema_version}; validation: {'OK' if not errs else 'FAILED: ' + '; '.join(errs)}.",
            "",
        ]
    return "\n".join(lines).rstrip() + "\n"


reg = _common.registry_from_args(args)
text = plugin_catalog(reg)
if args.output:
    os.makedirs(os.path.dirname(os.path.abspath(args.output)), exist_ok=True)
    with open(args.output, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"wrote {args.output}")
else:
    print(text)
if args.profiles_output:
    with open(args.profiles_output, "w", encoding="utf-8", newline="\n") as f:
        f.write(profile_catalog(reg))
    print(f"wrote {args.profiles_output}")
